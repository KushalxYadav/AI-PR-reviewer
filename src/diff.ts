/**
 * Markers inside the first few lines of a patch indicating an auto-generated file.
 */
const GENERATED_HEADER_MARKERS = [
  '@generated',
  'do not edit',
  'code generated by',
  'auto-generated',
  'autogenerated',
  'this file is generated',
];

export interface RawPullRequestFile {
  filename: string;
  status: string;
  additions: number;
  deletions: number;
  changes: number;
  patch?: string;
}

export interface DiffHunk {
  header: string;
  oldStart: number;
  oldLines: number;
  newStart: number;
  newLines: number;
  /** Raw patch lines belonging to this hunk (including the @@ header) */
  rawLines: string[];
  /** Formatted lines annotated with explicit RIGHT-side line numbers for the model */
  annotatedText: string;
  /** Set of valid RIGHT-side line numbers in this hunk */
  validRightLines: Set<number>;
}

export interface ParsedFileDiff {
  filename: string;
  status: string;
  additions: number;
  deletions: number;
  patch: string;
  hunks: DiffHunk[];
  /** All valid RIGHT-side line numbers across all hunks in this file */
  validRightLines: Set<number>;
  /** Formatted file diff block sent to Gemini */
  formattedPatch: string;
}

export interface DiffChunk {
  index: number;
  files: Array<{
    filename: string;
    status: string;
    formattedPatch: string;
  }>;
  totalChars: number;
}

export interface ChunkingResult {
  chunks: DiffChunk[];
  /** Files skipped due to max_files or max_total_chars caps */
  skippedForCostCap: string[];
}

/**
 * Escapes any closing `</UNTRUSTED_PR_DIFF>` tag inside untrusted diff or metadata
 * strings so a malicious PR cannot break out of the `<UNTRUSTED_PR_DIFF>` block.
 */
export function escapeUntrustedDiffTags(input: string): string {
  return input.replace(/<\s*\/\s*UNTRUSTED_PR_DIFF\s*>/gi, '&lt;/UNTRUSTED_PR_DIFF&gt;');
}

/**
 * Determines whether a file should be ignored as noise (lockfiles, minified files,
 * build/dist folders, binaries, generated files, or user-configured ignore globs).
 */
export function shouldIgnoreFile(
  filename: string,
  patch: string | undefined,
  userIgnoreGlobs: string[] = [],
  status?: string,
): { ignored: boolean; reason?: string } {
  const normalizedPath = filename.replace(/\\/g, '/').replace(/^\/+/, '');
  const baseName = normalizedPath.split('/').pop()?.toLowerCase() ?? '';

  if (status === 'removed') {
    return { ignored: true, reason: 'deleted file' };
  }

  if (!patch || patch.trim().length === 0) {
    return { ignored: true, reason: 'binary or empty patch' };
  }

  if (LOCKFILE_NAMES.has(baseName)) {
    return { ignored: true, reason: 'lockfile' };
  }

  for (const pattern of BUILTIN_NOISE_GLOBS) {
    if (minimatch(normalizedPath, pattern, { dot: true, nocase: true })) {
      return { ignored: true, reason: `built-in noise pattern (${pattern})` };
    }
  }

  // Check first 10 lines of patch for generated file markers
  const headSample = patch.split('\n').slice(0, 10).join('\n').toLowerCase();
  for (const marker of GENERATED_HEADER_MARKERS) {
    if (headSample.includes(marker)) {
      return { ignored: true, reason: `generated file (${marker})` };
    }
  }

  // Check if any added line is extremely long (> 2000 chars on a single line -> minified)
  const lines = patch.split('\n');
  for (const line of lines) {
    if (line.startsWith('+') && line.length > 2000) {
      return { ignored: true, reason: 'minified content' };
    }
  }

  for (const userPattern of userIgnoreGlobs) {
    const cleanPattern = userPattern.trim();
    if (!cleanPattern) continue;
    if (
      minimatch(normalizedPath, cleanPattern, {
        dot: true,
        matchBase: !cleanPattern.includes('/'),
      })
    ) {
      return { ignored: true, reason: `user ignore pattern (${cleanPattern})` };
    }
  }

  return { ignored: false };
}

const HUNK_HEADER_REGEX = /^@@\s+-(\d+)(?:,(\d+))?\s+\+(\d+)(?:,(\d+))?\s+@@(.*)$/;

/**
 * Parses a unified diff patch for a single file into structured hunks and computes
 * the exact set of valid RIGHT-side line numbers that GitHub's review API accepts.
 */
export function parseFilePatch(
  filename: string,
  patch: string,
  status = 'modified',
  additions = 0,
  deletions = 0,
): ParsedFileDiff {
  const rawLines = patch.replace(/\r\n/g, '\n').split('\n');
  const hunks: DiffHunk[] = [];
  const validRightLines = new Set<number>();

  let currentHunk: DiffHunk | null = null;
  let currentAnnotatedLines: string[] = [];
  let rightLineNumber = 0;

  const flushCurrentHunk = () => {
    if (currentHunk) {
      currentHunk.annotatedText = currentAnnotatedLines.join('\n');
      hunks.push(currentHunk);
      currentHunk = null;
      currentAnnotatedLines = [];
    }
  };

  for (const rawLine of rawLines) {
    const headerMatch = rawLine.match(HUNK_HEADER_REGEX);
    if (headerMatch) {
      flushCurrentHunk();
      const oldStart = parseInt(headerMatch[1], 10);
      const oldLines = headerMatch[2] !== undefined ? parseInt(headerMatch[2], 10) : 1;
      const newStart = parseInt(headerMatch[3], 10);
      const newLines = headerMatch[4] !== undefined ? parseInt(headerMatch[4], 10) : 1;

      rightLineNumber = newStart;
      currentHunk = {
        header: rawLine,
        oldStart,
        oldLines,
        newStart,
        newLines,
        rawLines: [rawLine],
        annotatedText: '',
        validRightLines: new Set<number>(),
      };
      currentAnnotatedLines.push(rawLine);
      continue;
    }

    if (!currentHunk) {
      continue;
    }

    currentHunk.rawLines.push(rawLine);

    if (rawLine.startsWith('+')) {
      currentHunk.validRightLines.add(rightLineNumber);
      validRightLines.add(rightLineNumber);
      currentAnnotatedLines.push(`L${rightLineNumber}: ${rawLine}`);
      rightLineNumber += 1;
    } else if (rawLine.startsWith('-')) {
      // Deleted lines exist only on the LEFT side; they do not advance RIGHT line number
      currentAnnotatedLines.push(`     ${rawLine}`);
    } else if (rawLine.startsWith(' ')) {
      currentHunk.validRightLines.add(rightLineNumber);
      validRightLines.add(rightLineNumber);
      currentAnnotatedLines.push(`L${rightLineNumber}: ${rawLine}`);
      rightLineNumber += 1;
    } else if (rawLine.startsWith('\\')) {
      // "\ No newline at end of file"
      currentAnnotatedLines.push(`     ${rawLine}`);
    }
  }

  flushCurrentHunk();

  const escapedFilename = escapeUntrustedDiffTags(filename);
  const formattedHunks = hunks.map((h) => escapeUntrustedDiffTags(h.annotatedText)).join('\n');
  const formattedPatch = `=== FILE: ${escapedFilename} (status: ${status}) ===\n${formattedHunks}`;

  return {
    filename,
    status,
    additions,
    deletions,
    patch,
    hunks,
    validRightLines,
    formattedPatch,
  };
}

/**
 * Splits parsed file diffs into chunks that fit within `maxChunkChars` while enforcing
 * overall `maxFiles` and `maxTotalChars` cost limits.
 *
 * Rules:
 * 1. Prefer keeping whole files together in a chunk.
 * 2. If a single file has multiple hunks and exceeds `maxChunkChars`, split it across
 *    hunk boundaries—NEVER split a single hunk in the middle.
 * 3. If a single hunk itself exceeds `maxTotalChars`, skip the file and record it in
 *    `skippedForCostCap`.
 */
export function chunkParsedDiffs(
  files: ParsedFileDiff[],
  maxChunkChars: number,
  maxTotalChars: number,
  maxFiles: number,
): ChunkingResult {
  const chunks: DiffChunk[] = [];
  const skippedForCostCap: string[] = [];

  let totalCharsUsed = 0;
  let filesIncluded = 0;

  let currentChunkFiles: DiffChunk['files'] = [];
  let currentChunkChars = 0;

  const flushChunk = () => {
    if (currentChunkFiles.length > 0) {
      chunks.push({
        index: chunks.length + 1,
        files: currentChunkFiles,
        totalChars: currentChunkChars,
      });
      currentChunkFiles = [];
      currentChunkChars = 0;
    }
  };

  for (const file of files) {
    if (file.hunks.length === 0) {
      continue;
    }

    if (filesIncluded >= maxFiles) {
      skippedForCostCap.push(file.filename);
      continue;
    }

    const fileChars = file.formattedPatch.length;

    // Check total budget for the run
    if (totalCharsUsed + fileChars > maxTotalChars) {
      skippedForCostCap.push(file.filename);
      continue;
    }

    filesIncluded += 1;
    totalCharsUsed += fileChars;

    // Case 1: The entire file fits within a single chunk
    if (fileChars <= maxChunkChars) {
      if (currentChunkChars + fileChars > maxChunkChars && currentChunkFiles.length > 0) {
        flushChunk();
      }
      currentChunkFiles.push({
        filename: file.filename,
        status: file.status,
        formattedPatch: file.formattedPatch,
      });
      currentChunkChars += fileChars;
      continue;
    }

    // Case 2: File is larger than maxChunkChars, so split along whole hunk boundaries
    flushChunk();
    const escapedFilename = escapeUntrustedDiffTags(file.filename);
    const fileHeader = `=== FILE: ${escapedFilename} (status: ${file.status}) ===\n`;

    let hunkGroupText = fileHeader;
    for (const hunk of file.hunks) {
      const escapedHunk = escapeUntrustedDiffTags(hunk.annotatedText);
      const candidateLength = hunkGroupText.length + escapedHunk.length + 1;

      if (hunkGroupText !== fileHeader && candidateLength > maxChunkChars) {
        chunks.push({
          index: chunks.length + 1,
          files: [
            {
              filename: file.filename,
              status: file.status,
              formattedPatch: hunkGroupText.trimEnd(),
            },
          ],
          totalChars: hunkGroupText.length,
        });
        hunkGroupText = `${fileHeader}${escapedHunk}\n`;
      } else {
        hunkGroupText += `${escapedHunk}\n`;
      }
    }

    if (hunkGroupText !== fileHeader) {
      chunks.push({
        index: chunks.length + 1,
        files: [
          {
            filename: file.filename,
            status: file.status,
            formattedPatch: hunkGroupText.trimEnd(),
          },
        ],
        totalChars: hunkGroupText.length,
      });
    }
  }

  flushChunk();

  return {
    chunks,
    skippedForCostCap,
  };
}

/**
 * Checks whether a given 1-based RIGHT-side line number is part of the parsed diff for a file.
 */
export function isValidRightDiffLine(fileDiff: ParsedFileDiff, line: number): boolean {
  return fileDiff.validRightLines.has(line);
}

/**
 * Filters findings so only those referencing a reviewed file and a valid RIGHT-side
 * diff line are kept. Returns both valid findings and dropped count.
 */
export function filterFindingsByDiffLines(
  findings: Finding[],
  parsedFilesByPath: Map<string, ParsedFileDiff>,
): { validFindings: Finding[]; droppedFindings: Finding[] } {
  const validFindings: Finding[] = [];
  const droppedFindings: Finding[] = [];

  for (const finding of findings) {
    const normalizedFile = finding.file.replace(/\\/g, '/').replace(/^\/+/, '');
    const fileDiff = parsedFilesByPath.get(normalizedFile) ?? parsedFilesByPath.get(finding.file);

    if (!fileDiff || !isValidRightDiffLine(fileDiff, finding.line)) {
      droppedFindings.push(finding);
      continue;
    }

    validFindings.push({
      ...finding,
      file: fileDiff.filename,
    });
  }

  return { validFindings, droppedFindings };
}
